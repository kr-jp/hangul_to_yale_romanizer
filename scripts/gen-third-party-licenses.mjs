#!/usr/bin/env node
// 배포 번들에 포함되는 서드파티 패키지의 라이선스 고지를 public/third-party-licenses.txt로 생성한다.
// 빌드 산출물(JS·CSS)은 최소화 과정에서 라이선스 주석이 빠지므로 별도 파일로 함께 배포한다 (npm run build 직전 자동 실행).
// 대상: package.json dependencies의 전이 의존성 전부 + CSS로 포함되는 tailwindcss·tw-animate-css
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const CSS_PACKAGES = ['tailwindcss', 'tw-animate-css'];

// Node의 node_modules 탐색 규칙대로 from에서 위로 올라가며 패키지 디렉터리를 찾는다
function findPackageDir(name, from) {
  for (let dir = from; ; dir = dirname(dir)) {
    const candidate = join(dir, 'node_modules', name);
    if (existsSync(join(candidate, 'package.json'))) return candidate;
    if (dirname(dir) === dir) return null;
  }
}

const found = new Map(); // dir → package.json
function visit(name, from) {
  const dir = findPackageDir(name, from);
  if (!dir || found.has(dir)) return;
  const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  found.set(dir, meta);
  for (const dep of Object.keys({ ...meta.dependencies, ...meta.optionalDependencies })) visit(dep, dir);
}
for (const name of [...Object.keys(pkg.dependencies || {}), ...CSS_PACKAGES]) visit(name, root);

const missing = [];
const sections = [...found.entries()]
  .sort(([, a], [, b]) => a.name.localeCompare(b.name))
  .map(([dir, meta]) => {
    const license = meta.license || (meta.licenses || []).map((l) => l.type).join(' OR ') || 'UNKNOWN';
    const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)/i.test(f));
    if (!file) missing.push(meta.name);
    // 라이선스 파일이 없는 패키지는 package.json의 저작자·저장소 정보를 그대로 싣는다
    const author = typeof meta.author === 'string' ? meta.author : meta.author?.name;
    const repo = typeof meta.repository === 'string' ? meta.repository : meta.repository?.url;
    const text = file
      ? readFileSync(join(dir, file), 'utf8').trim()
      : [`License: ${license}`, author && `Author: ${author}`, repo && `Repository: ${repo}`].filter(Boolean).join('\n');
    return `${meta.name}@${meta.version} (${license})\n${'-'.repeat(60)}\n${text}\n`;
  });

const header = [
  'Third-party software notices — Hangul ↔ Yale Romanizer',
  '',
  'This web app bundles the open-source packages listed below. Each is distributed under its own',
  'license, reproduced here as required. The app itself is MIT-licensed; the syllable frequency data',
  '(data/syllable-freq.json) is CC BY-SA 4.0 — see NOTICE.md in the repository.',
  '',
  `Generated by scripts/gen-third-party-licenses.mjs (${found.size} packages).`,
  '',
].join('\n');

mkdirSync(join(root, 'public'), { recursive: true });
writeFileSync(join(root, 'public', 'third-party-licenses.txt'), header + '\n' + sections.join('\n'));
console.log(`third-party-licenses.txt: ${found.size} packages` + (missing.length ? ` (no license file: ${missing.join(', ')})` : ''));
